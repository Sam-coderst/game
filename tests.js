"use strict";
const assert = require("assert");
const Core = require("./core.js");

const diagonal = Core.normalizedInput(1, 1);
assert.ok(Math.abs(diagonal.x - Math.SQRT1_2) < 1e-12);
assert.ok(Math.abs(diagonal.y - Math.SQRT1_2) < 1e-12);
assert.strictEqual(Math.hypot(diagonal.x, diagonal.y).toFixed(8), "1.00000000");
assert.deepStrictEqual([1,5,6,10,11,15,16,20].map(Core.multiplierForLoad), [1,1,1.2,1.2,1.5,1.5,2,2]);
assert.deepStrictEqual([5,10,15,20].map(Core.deliveryScore), [50,120,225,400]);
assert.strictEqual(Core.impactDropCount(Core.CONFIG.collisionImpactThreshold - 1, 20), 0);
assert.strictEqual(Core.impactDropCount(250, 20), 1);
assert.strictEqual(Core.impactDropCount(320, 20), 2);
assert.strictEqual(Core.impactDropCount(420, 2), 2);
assert.strictEqual(Core.clamp(22, 0, Core.CONFIG.maxLoad), 20);
